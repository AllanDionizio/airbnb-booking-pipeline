"""
Regression suite: every synthetic fixture must parse to its expected output.

Each JSON file under tests/fixtures/ holds one email (subject, date, body)
and the parser output written by hand for it. The files are generated by
`make fixtures`; the last test fails when they drift from the generator.
"""

import json
from datetime import datetime
from pathlib import Path

import pytest

from airbnb_booking_pipeline.parsers import parse_cancellation, parse_confirmation
from airbnb_booking_pipeline.synthetic.fixtures import build_fixtures

FIXTURES = Path(__file__).parents[1] / "fixtures"


def _load(kind: str) -> list:
    return [
        pytest.param(json.loads(path.read_text(encoding="utf-8")), id=path.stem)
        for path in sorted((FIXTURES / kind).glob("*.json"))
    ]


@pytest.mark.parametrize("fixture", _load("confirmations"))
def test_confirmation(fixture):
    booking = parse_confirmation(
        fixture["body"],
        subject=fixture["subject"],
        email_date=datetime.fromisoformat(fixture["email_date"]),
    )

    assert booking.to_dict() == fixture["expected"]


@pytest.mark.parametrize("fixture", _load("cancellations"))
def test_cancellation(fixture):
    notice = parse_cancellation(fixture["body"], subject=fixture["subject"])

    assert notice.to_dict() == fixture["expected"]


def test_committed_fixtures_match_the_generator():
    committed = {
        path.relative_to(FIXTURES).as_posix(): path.read_text(encoding="utf-8")
        for path in FIXTURES.rglob("*.json")
    }

    assert committed == build_fixtures(), "fixtures are stale: run `make fixtures`"
